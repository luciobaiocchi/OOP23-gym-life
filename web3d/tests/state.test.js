import test from 'node:test';
import assert from 'node:assert/strict';
import { GameState, FOODS } from '../src/state.js';
import { timingScore } from '../src/training.js';
import { levelFor, restoreCareer } from '../src/progression.js';

test('old saves migrate with safe career defaults and preserve progress', () => {
  const state = GameState.fromSave({ difficulty: 'hard', days: 14, money: 75, stamina: 46, happiness: 53, legs: 20, chest: 30, back: 40, inventory: { broccoli: 4 } });
  assert.equal(state.day, 7);
  assert.equal(state.mass, 90);
  assert.equal(state.money, 75);
  assert.deepEqual(state.inventory, { hamburger: 0, broccoli: 4, meat: 0 });
  assert.equal(state.career.xp, 0);
  assert.equal(state.career.daily.claimed, false);
});
test('malformed saves cannot replace model methods or inject invalid stats', () => {
  const state = GameState.fromSave({ difficulty: 'constructor', totalDays: 99999, days: -8, stamina: NaN, happiness: Infinity, legs: 999, chest: -10, apply: 'broken', inventory: { hamburger: -1, meat: 1e8 }, career: { xp: Infinity, completed: { includes: 1 }, secrets: 'legday', best: { squat: 10 }, recovery: { water: null } } });
  assert.equal(state.difficulty, 'medium');
  assert.equal(state.totalDays, 30);
  assert.equal(state.days, 0);
  assert.equal(state.legs, 100);
  assert.equal(state.chest, 0);
  assert.equal(state.stamina, 100);
  assert.equal(state.inventory.meat, 999);
  assert.equal(typeof state.apply, 'function');
  assert.deepEqual(state.career.secrets, []);
  assert.equal(state.career.best.squat, 1);
  assert.equal(restoreCareer(null).sessions, 0);
});
test('quest, daily and medal payouts happen once and survive reloading', () => {
  let s = new GameState();
  const first = s.completeActivity('basket', 0.9, 0);
  assert.equal(first.medal, true);
  assert.ok(first.quests.some(q => q.id === 'fresh_air'));
  assert.ok(first.quests.some(q => q.id === 'precision'));
  s = GameState.fromSave(JSON.parse(JSON.stringify(s)));
  const second = s.completeActivity('basket', 0.9, 0);
  assert.equal(second.medal, false);
  assert.equal(second.quests.length, 0);
  assert.equal(second.personalBest, false);
  const third = s.completeActivity('boxing', 0.5, 0);
  assert.equal(third.daily, true);
  assert.equal(s.completeActivity('boxing', 0.5, 0).daily, false);
  s.sleep();
  s.completeActivity('lat', 1);
  s.completeActivity('bench', 1);
  assert.equal(s.completeActivity('squat', 1).daily, true);
});
test('every muscle and outdoor sport contributes to distinct missions', () => {
  const s = new GameState();
  for (const id of ['squat', 'bench', 'lat', 'basket', 'boxing', 'run']) s.completeActivity(id, 0.75);
  assert.equal(s.career.workouts, 3);
  assert.equal(s.career.outdoor, 3);
  assert.ok(s.career.completed.includes('balanced'));
  assert.ok(s.career.completed.includes('athlete'));
  assert.equal(Object.keys(s.career.best).length, 6);
  assert.equal(s.completeActivity('unknown', 1), null);
  assert.equal(s.completeActivity('squat', NaN), null);
});
test('secret collection is permanent, unique and rewards the full set once', () => {
  let s = new GameState();
  s.collectSecret('legday');
  const money = s.money;
  assert.equal(s.collectSecret('legday'), null);
  assert.equal(s.money, money);
  s = GameState.fromSave(JSON.parse(JSON.stringify(s)));
  assert.equal(s.collectSecret('legday'), null);
  s.collectSecret('lightweight');
  assert.equal(s.collectSecret('disco')[0].id, 'treasure');
  assert.equal(s.money, 40 + 3 * 15 + 75);
  assert.equal(s.collectSecret('fake'), null);
});
test('daily recovery persists across loads and resets after sleep', () => {
  let s = new GameState();
  s.stamina = 30;
  assert.deepEqual(s.recover('water'), { stamina: 12 });
  assert.equal(s.stamina, 42);
  s = GameState.fromSave(JSON.parse(JSON.stringify(s)));
  assert.equal(s.recover('water'), null);
  assert.equal(s.recover('constructor'), null);
  s.sleep(); s.stamina = 20;
  assert.ok(s.recover('water'));
  assert.equal(s.stamina, 32);
});
test('food is useful, finite and never creates negative inventory or money', () => {
  const s = new GameState();
  s.stamina = 10;
  assert.equal(s.eat('meat'), true);
  assert.equal(s.stamina, 10 + FOODS.meat.stamina);
  assert.equal(s.eat('meat'), false);
  assert.equal(s.buy('toString'), false);
  assert.equal(s.eat('toString'), false);
  s.money = 0;
  assert.equal(s.buy('meat'), false);
  const chest = s.chest;
  s.apply({ days: 200, money: NaN, chest: Infinity });
  assert.equal(s.days, 30);
  assert.equal(s.money, 0);
  assert.equal(s.chest, chest);
});
test('exercise affordability reserves enough energy to remain alive', () => {
  const s = new GameState();
  s.stamina = s.workoutCost;
  assert.equal(s.canWorkout(), false);
  s.stamina++;
  assert.equal(s.canWorkout(), true);
  s.apply({ stamina: -s.workoutCost });
  assert.equal(s.gameOverReason(), null);
});
test('league levels and skill timing reward precision consistently', () => {
  assert.equal(levelFor(0), 1);
  assert.equal(levelFor(80), 2);
  assert.equal(levelFor(320), 3);
  assert.equal(levelFor(1280), 5);
  assert.equal(levelFor(1e9), 10);
  assert.equal(timingScore(0.6, 0.6, 0.2), 1);
  assert.equal(timingScore(0.67, 0.6, 0.2), 0.78);
  assert.equal(timingScore(0.75, 0.6, 0.2), 0.35);
  assert.equal(timingScore(0.95, 0.6, 0.2), 0);
});
